"""Collect the numbers shown on the interactive page (docs/index.html) from the committed result files.

Usage: python docs/build_data.py   (writes docs/data.js)

Every value on the page comes from out/final/results.json, out/final/step4.json and out/final/explorer.json;
nothing is typed by hand into the page.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out" / "final"


def r(x, k=4):
    return round(float(x), k)


def est(v, k=4):
    return {"est": r(v["estimate"], k), "lo": r(v["ci95"][0], k), "hi": r(v["ci95"][1], k)}


def main():
    R = json.loads((OUT / "results.json").read_text())
    S4 = json.loads((OUT / "step4.json").read_text())
    X = json.loads((OUT / "explorer.json").read_text())
    s1, s2, s3 = R["step1"], R["step2"], R["step3"]
    pv2, pv3, off = s2["policy_value_top10pct"], s3["policy_value_top10pct"], s2["usual_offline_check"]
    names = ["long_view", "watch_seconds", "completion", "duration"]
    D = {
        "test": {"users": R["test"]["users"], "exposures": R["test"]["random_exposures"],
                 "long_view_random": r(R["test"]["long_view_rate_random"]),
                 "long_view_standard_feed": r(R["test"]["long_view_rate_standard_feed"])},
        "step1": {k: {"auc": r(v["auc"]), "within": est(v["within_user_auc"]), "top_long_view": est(v["top10pct_long_view"])}
                  for k, v in s1["models"].items()},
        "step2": {"top": {k: {n: est(pv2[k][n]) for n in ("long_view", "watch_seconds")} for k in pv2},
                  "offline": {k: {"auc_standard": r(v["auc_on_standard_feed"]), "within_random": r(v["within_user_auc_on_random_exposures"]),
                                  "pred_over_actual": r(v["predicted_over_actual_on_random_exposures"], 2)} for k, v in off.items()},
                  "difference_long_view": est(s2["difference_long_view"])},
        "step3": {k: {n: est(v[n]) for n in names} for k, v in pv3.items()},
        "step3_diff_watch": est(s3["watch_time_minus_completion__watch_seconds"], 2),
        "step3_completion_vs_random": est(s3["completion_minus_random__watch_seconds"], 2),
        "shares": X["shares"], "random": X["random"], "curves": X["curves"], "calibration": X["calibration"],
        "length_edges": X["length_edges"], "length_of_picks": X["length_of_picks"],
        "step4": {"videos": S4["videos"]["test"], "exposures": S4["test_exposures"], "users": S4["test_users"],
                  "auc": {k: est(v) for k, v in S4["within_user_auc"].items()},
                  "corr": {k: r(v["weighted_pearson_with_observed_rate"], 3) for k, v in S4["video_level"].items()},
                  "by_decile": X["cold_start"]["by_decile"], "overall_rate": X["cold_start"]["overall_rate"],
                  "scatter": X["cold_start"]["scatter"]},
    }
    js = "// Generated by docs/build_data.py from the result files of the repository. Do not edit by hand.\n"
    (ROOT / "docs" / "data.js").write_text(js + "window.DATA = " + json.dumps(D, separators=(",", ":")) + ";\n")
    print("wrote docs/data.js", round(len(json.dumps(D)) / 1024), "KB")


if __name__ == "__main__":
    main()
